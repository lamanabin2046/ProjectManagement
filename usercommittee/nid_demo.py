def find(nid):
    return _BY_DIGITS.get(digits(nid))


def api_response(nid):
    """(http_status, body) — डेमो server र `NID_API_URL=demo` दुवैले प्रयोग गर्छन्।"""
    if len(digits(nid)) != NID_DIGITS:
        return 400, {"status": "invalid", "message": "NID ९ अङ्कको हुनुपर्छ (उदाहरण: 435-6756-65)।"}
    person = find(nid)
    if not person:
        return 404, {"status": "not_found", "message": "यो NID राष्ट्रिय परिचयपत्र अभिलेखमा भेटिएन।"}
