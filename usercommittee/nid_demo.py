NID_DIGITS = 9  # ढाँचा: XXX-XXXX-XX


def digits(nid):
    return re.sub(r"\D", "", (nid or "").translate(_NP))


def fmt(nid):
    """'435675665' / '४३५६७५६६५' -> '435-6756-65' (९ अङ्क नभए जस्ताको तस्तै)."""
    d = digits(nid)
    return f"{d[:3]}-{d[3:7]}-{d[7:]}" if len(d) == NID_DIGITS else (nid or "").strip()


